create extension if not exists pg_trgm;
create extension if not exists unaccent;

alter table public.anime
  add column if not exists normalized_title text;

create or replace function public.normalize_anime_title(value text)
returns text
language sql
stable
parallel safe
as $$
  select trim(regexp_replace(lower(public.unaccent(coalesce(value, ''))), '[^[:alnum:]]+', ' ', 'g'));
$$;

update public.anime
set normalized_title = public.normalize_anime_title(coalesce(title_english, title_romaji, ''))
where normalized_title is null;

create or replace function public.set_anime_normalized_title()
returns trigger
language plpgsql
as $$
begin
  new.normalized_title := public.normalize_anime_title(coalesce(new.title_english, new.title_romaji, ''));
  return new;
end;
$$;

drop trigger if exists trg_anime_normalized_title on public.anime;
create trigger trg_anime_normalized_title
before insert or update of title_english, title_romaji on public.anime
for each row execute function public.set_anime_normalized_title();

create table if not exists public.anime_title_aliases (
  id bigint generated by default as identity primary key,
  anime_id integer not null references public.anime(id) on delete cascade,
  alias text not null,
  normalized_alias text not null,
  alias_type text not null default 'source_synonym',
  language text,
  source text not null,
  source_id text,
  provenance_url text,
  observed_at timestamptz not null default now(),
  source_updated_at timestamptz,
  created_at timestamptz not null default now(),
  unique (anime_id, source, normalized_alias)
);

create index if not exists anime_normalized_title_btree
  on public.anime (normalized_title);
create index if not exists anime_normalized_title_trgm
  on public.anime using gin (normalized_title gin_trgm_ops);
create index if not exists anime_alias_normalized_btree
  on public.anime_title_aliases (normalized_alias);
create index if not exists anime_alias_normalized_trgm
  on public.anime_title_aliases using gin (normalized_alias gin_trgm_ops);
create index if not exists anime_alias_anime_id
  on public.anime_title_aliases (anime_id);

create table if not exists public.source_identities (
  id bigint generated by default as identity primary key,
  anime_id integer not null references public.anime(id) on delete cascade,
  source text not null,
  source_id text not null,
  canonical_title text,
  confidence numeric(5,4) check (confidence is null or (confidence >= 0 and confidence <= 1)),
  review_status text not null default 'accepted' check (review_status in ('candidate', 'accepted', 'rejected', 'needs_review')),
  provenance_url text,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  unique (source, source_id)
);

create index if not exists source_identities_anime_id
  on public.source_identities (anime_id);

alter table public.anime enable row level security;
alter table public.anime_title_aliases enable row level security;
alter table public.source_identities enable row level security;

