create or replace function public.search_anime_titles(
  p_query text,
  p_limit integer default 24,
  p_offset integer default 0
)
returns table (
  anime_id integer,
  title_english text,
  title_romaji text,
  cover_image_url text,
  matched_alias text,
  match_source text,
  match_score real,
  ambiguous_count bigint
)
language sql
stable
security invoker
set search_path = public, extensions
as $$
  with normalized_query as (
    select public.normalize_anime_title(trim(coalesce(p_query, ''))) as value
  ),
  candidates as (
    select
      a.id,
      a.title_english,
      a.title_romaji,
      a.cover_image_url,
      coalesce(a.title_english, a.title_romaji) as matched_alias,
      'canonical'::text as match_source,
      greatest(
        case when a.normalized_title = q.value then 1.0 else 0.0 end,
        case when a.normalized_title like q.value || '%' then 0.85 else 0.0 end,
        similarity(a.normalized_title, q.value)
      )::real as match_score
    from public.anime a
    cross join normalized_query q
    where q.value <> ''
      and (a.normalized_title = q.value or a.normalized_title like q.value || '%' or a.normalized_title % q.value)

    union all

    select
      a.id,
      a.title_english,
      a.title_romaji,
      a.cover_image_url,
      aliases.alias as matched_alias,
      aliases.source,
      greatest(
        case when aliases.normalized_alias = q.value then 0.98 else 0.0 end,
        case when aliases.normalized_alias like q.value || '%' then 0.83 else 0.0 end,
        similarity(aliases.normalized_alias, q.value)
      )::real
    from public.anime_title_aliases aliases
    join public.anime a on a.id = aliases.anime_id
    cross join normalized_query q
    where q.value <> ''
      and (aliases.normalized_alias = q.value or aliases.normalized_alias like q.value || '%' or aliases.normalized_alias % q.value)
  ),
  best as (
    select distinct on (c.id)
      c.*,
      count(*) over (partition by c.id)::bigint as ambiguous_count
    from candidates c
    order by c.id, c.match_score desc, c.matched_alias
  )
  select
    b.id,
    b.title_english,
    b.title_romaji,
    b.cover_image_url,
    b.matched_alias,
    b.match_source,
    b.match_score,
    b.ambiguous_count
  from best b
  order by b.match_score desc, coalesce(b.title_english, b.title_romaji), b.id
  limit least(greatest(coalesce(p_limit, 24), 1), 50)
  offset greatest(coalesce(p_offset, 0), 0);
$$;

grant execute on function public.search_anime_titles(text, integer, integer) to anon, authenticated;

